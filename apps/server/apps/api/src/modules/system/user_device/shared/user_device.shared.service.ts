import type { EntityManager } from 'typeorm'
import { Injectable, Logger } from '@nestjs/common'
import { isDev } from '@walnut-server/config/utils/env'
import { AppDayjs } from '@walnut-server/utils/dayjs'
import { isNil } from 'lodash'
import { AppMonitorUserRepositoryService } from '@/modules/app/monitor/user/repo/user.repo.service'
import { SysDeviceRepositoryService } from '../../device/repo/device.repo.service'
import { SysDeviceSharedService } from '../../device/shared/device.shared.service'
import { SysUserDeviceRepositoryService } from '../repo/user_device.repo.service'

/**
 * B6 迁移：事务句柄签名 `dbSession?: ClientSession` → `em?: EntityManager`
 * （本模块数据面已全量在 PG；仍有 Mongo 写腿的消费方（auth 系）经编译期红点逐一把
 * session 参数摘除，见各消费方适配注释）。
 */
@Injectable()
export class SysUserDeviceSharedService {
  private readonly logger = new Logger(SysUserDeviceSharedService.name)

  constructor(
    private readonly userDeviceRepo: SysUserDeviceRepositoryService,
    private readonly appMonitorUserRepo: AppMonitorUserRepositoryService,

    private readonly deviceRepo: SysDeviceRepositoryService,
    private readonly deviceSharedService: SysDeviceSharedService,
  ) {}

  /**
   * @description get trusted devices of user
   */
  async getUserDeviceTrusted(
    userId: string,
    deviceId: string,
    em?: EntityManager,
  ) {
    const device = await this.userDeviceRepo.findTrustedDevice(
      userId,
      deviceId,
      em,
    )
    return this.userDeviceRepo.isTrustedAndValid(device)
  }

  /**
   * @description get all users by device id
   * （基线语义原样保留：Mongo 版这个 filter 只放行 populated_user 缺失的行 —— 看似
   * 反转、实为现状行为，PG 侧只把判等键从 _id 换成 id，不做"修正"）
   */
  async getAllUsersByDeviceId(deviceId: string) {
    const docs = await this.userDeviceRepo.findAllUserInCurrentDevice(deviceId)
    return docs
      .filter(i => isNil(i.populated_user?.id))
      .map(i => ({
        ...(i.populated_user ?? {}),
        lastActiveAt: i.lastActiveAt,
      }))
  }

  /**
   * @description bind device for user
   * @returns new document
   */
  async bindDeviceForUser(
    userId: string,
    deviceId: string,
    em?: EntityManager,
  ) {
    this.logger.log(`Bind device for user, userId: ${userId}, deviceId: ${deviceId}`)
    const deviceName = await this.deviceRepo.getDeviceNameByDeviceId(
      deviceId,
      em,
    )

    this.logger.log(`Extracted Device name: ${deviceName}`)

    return this.userDeviceRepo.upsertDevice(
      userId,
      deviceId,
      deviceName,
      em,
    )
  }

  /**
   * @description update trusted status for user device
   */
  async updateTrustedStatusForUserDevice(
    userId: string,
    deviceId: string,
    trusted: boolean,
    em?: EntityManager,
  ) {
    const trustedExpiredAt = trusted
      ? this.userDeviceRepo.getTrustedExpiredAt()
      : null

    return this.userDeviceRepo.updateTrustedStatus(
      userId,
      deviceId,
      trusted,
      trustedExpiredAt,
      em,
    )
  }

  /**
   * @description update device active status for cron jobs
   * violently deactivate devices that have not been active for last 5 minutes
   * execute this method every 5 minutes
   */
  async updateDeviceActiveStatusForCronJob() {
    if (isDev) {
      return {
        matchedCount: 0,
        modifiedCount: 0,
        deletedCount: 0,
      }
    }

    const thresholdTime = AppDayjs().subtract(5, 'minute').toDate()
    const activeDevices = await this.deviceRepo.getAllActiveDevices()

    let modifiedCount = 0
    let deletedCount = 0

    for (const device of activeDevices) {
      const monitorRecord = await this.appMonitorUserRepo.findActiveByDeviceId(device.deviceId)

      if (monitorRecord && monitorRecord.lastActiveAt !== null) {
        const isInactiveTooLong = AppDayjs(monitorRecord.lastActiveAt).isBefore(thresholdTime)

        if (isInactiveTooLong) {
          modifiedCount++
          await this.deviceSharedService.updateDeviceActive(device.deviceId, false)
        }
      }
      else {
        // no last active at, this means this device may been generated by api but not real browser activity
        // delete non-monitor user device
        const res = await this.deviceRepo.deleteNonMonitorUserDevice(device.deviceId)
        // also delete monitor record
        await this.appMonitorUserRepo.delMonitorByDeviceId(device.deviceId)

        if (res) {
          deletedCount++
        }
      }
    }

    return {
      matchedCount: activeDevices.length,
      modifiedCount,
      deletedCount,
    }
  }
}
