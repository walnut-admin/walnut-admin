import type { EntityManager } from 'typeorm'
import type { IWalnutAdminSystemDeviceKicker, IWalnutAdminSystemMonitorActiveUserReader } from '../system.ports'
import { Inject, Injectable, Logger } from '@nestjs/common'
import { AppTechCacheDeviceService } from '@walnut-server/cache'
import { WalnutAdminConstRevokeRTType } from '@walnut-server/const/app/setting'
import { registerAfterCommitHook, runAfterCommit } from '@walnut-server/db'
import { WalnutAdminExceptionBadRequest } from '@walnut-server/exceptions/base.exception'
import { WalnutAdminExceptionDataNotFound } from '@walnut-server/exceptions/base/404'

import { WalnutAdminExceptionDeviceNotAcceptable } from '@walnut-server/exceptions/base/406'
import { SysUserDeviceSharedService } from '@walnut-server/identity'
import { SharedIpService } from '@walnut-server/ip'
import { DeviceTypeConst, IDeviceTypeConst } from '@walnut-server/list'
import { escapeLikePattern } from '@walnut-server/repository'
import { AppDayjs } from '@walnut-server/utils/dayjs'
import { omit } from 'lodash'
import { Brackets, QueryFailedError } from 'typeorm'
import { WALNUT_ADMIN_SYSTEM_DEVICE_KICKER, WALNUT_ADMIN_SYSTEM_MONITOR_ACTIVE_USER_READER } from '../system.ports'
import { SysDeviceBasicRepository } from './device.basic.repository'
import { SysDeviceDTOInitialRequest, SysDeviceDTOListRequest } from './dto/device.dto'
import { SysDeviceEntity } from './entity/device.entity'
import { SysDeviceRepositoryService } from './repo/device.repo.service'

const botPattern = /bot|crawl|slurp|spider/i
const tabletPattern = /Tablet|iPad/i
const mobilePattern = /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i

/**
 * B6 迁移：Mongo model → PG。`dbSession` → `em`（纯透传）；
 * initial 的 findOneAndUpdate(upsert) 改「按业务键 device_id 查到即整体覆盖、否则插入」，
 * 冲突路径（并发重复插入）由 uq_device_id 拒绝并进 catch，对齐 Mongo E11000 路径。
 *
 * F-31 重构（裁决 Q6=b）：**数据访问已下沉 repo** —— initial 原先自己
 * `em.getRepository(SysDeviceEntity)` 做 upsert（「服务即数据面」的第 4 形态），现在走
 * `SysDeviceBasicRepository.upsertByDeviceId`（同模块 Basic Repository），本服务只编排
 * （拼 deviceData、after-commit 双写缓存、冲突语义转业务错误）。SQL 语义、em 透传、
 * 返回形状均不变。
 */
@Injectable()
export class SysDeviceService {
  private readonly logger = new Logger(SysDeviceService.name)

  constructor(
    private readonly cacheDeviceService: AppTechCacheDeviceService,

    private readonly deviceBasicRepo: SysDeviceBasicRepository,
    @Inject(WALNUT_ADMIN_SYSTEM_MONITOR_ACTIVE_USER_READER)
    private readonly monitorActiveUserReader: IWalnutAdminSystemMonitorActiveUserReader,
    // 拍板-4：封禁 = 踢下线（撤 RT + 清会话键 + 断 WS），实现绑定在 app 的 @Global 模块
    @Inject(WALNUT_ADMIN_SYSTEM_DEVICE_KICKER)
    private readonly deviceKicker: IWalnutAdminSystemDeviceKicker,
    private readonly userDeviceSharedService: SysUserDeviceSharedService,
    private readonly deviceRepoService: SysDeviceRepositoryService,
    private readonly sharedIpService: SharedIpService,
  ) { }

  /**
   * @description get device id from request, generated by doubao
   */
  private getDeviceTypeByUA(userAgent: string, screenWidth: number): IDeviceTypeConst {
    if (botPattern.test(userAgent)) {
      return DeviceTypeConst.BOT
    }

    if (tabletPattern.test(userAgent)) {
      return DeviceTypeConst.TABLET
    }

    if (mobilePattern.test(userAgent)) {
      return DeviceTypeConst.MOBILE
    }

    if (screenWidth < 768) {
      return DeviceTypeConst.MOBILE
    }
    else if (screenWidth >= 768 && screenWidth < 1024) {
      return DeviceTypeConst.TABLET
    }

    return DeviceTypeConst.DESKTOP
  }

  /**
   * @description initial device - optimized version
   */
  async initial(req: IWalnutAdminExpressRequest, payload: SysDeviceDTOInitialRequest, em: EntityManager) {
    try {
      const deviceId = this.deviceRepoService.getDeviceIdByFingerprint(req.fingerprint)
      const locationInfo = await this.sharedIpService.getLocationInfoFromFreeAPI(req.realIp)

      const location = {
        country: locationInfo.country,
        region: locationInfo.region,
        city: locationInfo.city,
      }

      // $set 语义的整体覆盖集（Mongo 版 deviceData 原样字段集，sr/vp/geo 拍平为 PG 列）
      const deviceData: Partial<SysDeviceEntity> = {
        deviceName: payload.deviceName,
        private: payload.private,
        deviceId,
        srHeight: payload.sr?.height ?? null,
        srWidth: payload.sr?.width ?? null,
        vpHeight: payload.vp?.height ?? null,
        vpWidth: payload.vp?.width ?? null,
        deviceInfo: {
          ...payload.deviceInfo,
          os: req.os,
          browser: req.browser,
          type: this.getDeviceTypeByUA(req.userAgent?.ua as string, payload.sr.height),
        },
        hardwareInfo: (payload.hardwareInfo ?? null) as unknown as Record<string, unknown> | null,
        geoLongitude: locationInfo.longitude!,
        geoLatitude: locationInfo.latitude!,
        locationInfo: location,
        locationHistory: [
          {
            ip: req.realIp,
            location,
            timestamp: AppDayjs().valueOf(),
          },
        ],
        ipHistory: [req.realIp],
        ip: req.realIp,
        active: true,
        // 拍板-5：设备重新 initial = 又有真实浏览器活动，清掉 cron 打的 stale 标记
        // （stale 不参与鉴权，这里只维护「残留行」语义；banned / locked 不在写集，保持原值）
        stale: false,
      }

      // upsert：按业务键 device_id 查到即整体覆盖（$set + returnDocument: 'after'），否则插入
      // —— F-31：数据访问已下沉 repo，事务句柄 em 原样透传（同事务）
      const result = await this.deviceBasicRepo.upsertByDeviceId(deviceId, deviceData, em)

      registerAfterCommitHook(async () => {
        await this.cacheDeviceService.setSysDeviceCache(result)
        // P0-1：initial 刚签了 cookie，顺手把滑动续期的窗口开启 —— 否则紧接着的第一个
        // 受保护请求会立刻再重发一次（一个无意义的 Set-Cookie）
        await this.cacheDeviceService.markDeviceCookieRenewed(deviceId)
      })

      return {
        deviceId: result.deviceId,
        locationInfo,
      }
    }
    catch (err) {
      this.logger.error(err)

      // P3-2：重名 device_name 撞 uq_device_name（23505）在 catch-all 之前单列 ——
      // 客户端配置里设备名可复用时，这是「数据冲突」而非「设备不受支持」，受控 40000
      if (err instanceof QueryFailedError && (err.driverError as { code?: string })?.code === '23505') {
        throw new WalnutAdminExceptionBadRequest({
          _devMsg: 'device_name already exists (uq_device_name)',
        })
      }

      throw new WalnutAdminExceptionDeviceNotAcceptable()
    }
  }

  /**
   * @description read device by id
   * （PG 版 readById 查无即抛 DataNotFound，Mongo 版的 null 检查由基类承接）
   */
  async read(id: string) {
    return this.deviceBasicRepo.readById(id)
  }

  /**
   * @description list
   * （Mongo 版 location 过滤是 $expr + $regexMatch('i') 打在 locationInfo 三个子字段上 →
   * PG 侧 jsonb 提取 + ILIKE，字面量转义同 pg-list.builder）
   */
  async list(params: SysDeviceDTOListRequest) {
    const location = params.query.location ?? null

    const cleanParams = omit(params, ['query.location']) as SysDeviceDTOListRequest

    if (location === null) {
      return this.deviceBasicRepo.list(cleanParams)
    }

    // 字面量转义走 pg-column-op 的单一真源（与 list 主线、locale、deleted 同口径）
    const escaped = escapeLikePattern(String(location))

    return this.deviceBasicRepo.list(cleanParams, (qb) => {
      qb.andWhere(new Brackets((b) => {
        b.orWhere(`entity.location_info->>'country' ILIKE :location`, { location: `%${escaped}%` })
        b.orWhere(`entity.location_info->>'region' ILIKE :location`, { location: `%${escaped}%` })
        b.orWhere(`entity.location_info->>'city' ILIKE :location`, { location: `%${escaped}%` })
      }))
    })
  }

  /**
   * @description get current active user by device id
   */
  async getCurrentActiveUser(id: string) {
    const target = await this.deviceBasicRepo.readById(id)
    return this.monitorActiveUserReader.findActiveUserByDeviceId(target.deviceId)
  }

  /**
   * @description get history users by device id
   */
  async getHistoryUsersByDeviceId(id: string) {
    const target = await this.deviceBasicRepo.readById(id)
    return this.userDeviceSharedService.getAllUsersByDeviceId(target.deviceId)
  }

  /**
   * @description 更新设备锁/封标志（DB 为真源，事务提交后再双写 SYS_DEVICE 缓存）
   *
   * P2-2 修复（2026-10-28）：Mongo 版只置内存标志 + 写缓存、不落库 —— Redis 清空/
   * 过期即失效。sys_device 本就有 locked / banned 列（phase2 4.8），改为同事务更新
   * DB + after-commit 缓存双写；Device guard 缓存 miss 时回源库（见 device.guard）。
   */
  private async updateLockOrBanStatus(
    id: string,
    patch: Pick<Partial<SysDeviceEntity>, 'locked' | 'banned'>,
    em?: EntityManager,
  ) {
    const target = await this.deviceBasicRepo.readById(id, em)

    const updated = await this.deviceRepoService.findDeviceByDeviceIdAndUpdate(target.deviceId, patch, em)
    if (!updated) {
      // 行在本事务内被并发删除（readById 已通过）：按既有读腿语义回 40401
      throw new WalnutAdminExceptionDataNotFound()
    }

    await runAfterCommit(async () => {
      await this.cacheDeviceService.setSysDeviceCache(updated)
    })

    // 拍板-4（封禁 = 踢下线）：封禁不能只写行 —— 已封设备当时还能用 /auth/refresh 续
    // AT、WS 连接也不断。这里在**同一事务**里撤掉该设备上所有用户的 RT，事务提交后
    // 清会话键并断开该设备的 socket；解禁（banned=false）不触发任何踢人。
    if (patch.banned === true) {
      await this.deviceKicker.kickDevice(
        target.deviceId,
        WalnutAdminConstRevokeRTType.deviceBanned,
        em,
      )
    }

    return true
  }

  /**
   * @description lock device by id
   */
  async lock(id: string, em?: EntityManager) {
    return this.updateLockOrBanStatus(id, { locked: true }, em)
  }

  /**
   * @description unlock device by id
   */
  async unlock(id: string, em?: EntityManager) {
    return this.updateLockOrBanStatus(id, { locked: false }, em)
  }

  /**
   * @description ban device by id
   */
  async ban(id: string, em?: EntityManager) {
    return this.updateLockOrBanStatus(id, { banned: true }, em)
  }

  /**
   * @description unban device by id
   */
  async unban(id: string, em?: EntityManager) {
    return this.updateLockOrBanStatus(id, { banned: false }, em)
  }
}
