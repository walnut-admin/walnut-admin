/**
 * emoji 的 Unicode 范围 —— **这个文件是"两份实现"的共享部分**。
 *
 * 为什么单独一个文件：判定范围要被两处用（`lib/emoji.ts` 的门禁、以及
 * `@walnut/eslint-config` 那条规则里手写的一份）。放在这里至少让"改范围"有一个明确的落点，
 * 而不是散在正则字面量里（`emoji.ts` 顶部写了为什么不抽成跨包共享）。
 *
 * 范围的含义（刻意**不含** `U+2190–U+21FF` 箭头与 `U+2200–U+22FF` 数学算子 ——
 * 它们是排版符号，本仓注释大量在用，误报会让门禁变成噪声源）：
 *
 * - `U+1F000–U+1FAFF`：基本平面外的主流 emoji（代理对，终端乱码的重灾区）
 * - `U+2600–U+27BF`：杂项符号 + 装饰符号（警示三角、对勾、叉号那一类）
 * - `U+2B00–U+2BFF`、`U+23E9–U+23FA`：箭头装饰与媒体控制类（快进/暂停那一类）
 * - `U+FE0F`、`U+200D`：变体选择符与零宽连接符（"emoji 形态"那一位，也是乱码元凶）
 */
export const EMOJI_RANGES = '\\u{1F000}-\\u{1FAFF}\\u{2600}-\\u{27BF}\\u{2B00}-\\u{2BFF}\\u{23E9}-\\u{23FA}\\uFE0F\\u200D'
